using Microsoft.Build.Locator;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.MSBuild;
using System;
using System.IO.Abstractions;
using System.Threading;
using System.Threading.Tasks;

namespace Tarp.McDc;

/*
 * Instruments a project for MC/DC: writes a mirror of the project (rewritten sources, the project
 * file, the runtime) to the output directory, plus the map the report needs.
 *
 * NOTE: like TarpPreprocessor, it copies the project file as is, so it works for SDK-style projects
 * whose sources live under the project directory; project references and linked files don't resolve
 * from the mirror yet.
 */
public class McDcProjectInstrumenter
{
    public const string HitsDirectoryName = "tarp-hits";

    private readonly IFileSystem fileSystem;

    public McDcProjectInstrumenter(IFileSystem fileSystem)
    {
        this.fileSystem = fileSystem;
    }

    public async Task<McDcMap> InstrumentProject(string projectFilePath, string outputDir, CancellationToken cts)
    {
        outputDir = fileSystem.Path.GetFullPath(outputDir);
        fileSystem.Directory.CreateDirectory(outputDir);

        if (!MSBuildLocator.IsRegistered)
        {
            MSBuildLocator.RegisterDefaults();
        }

        using var workspace = MSBuildWorkspace.Create();

        var project = await workspace.OpenProjectAsync(projectFilePath, cancellationToken: cts).ConfigureAwait(false);
        if (project.Language != LanguageNames.CSharp)
        {
            throw new InvalidOperationException($"{projectFilePath} is not a C# project");
        }

        var compilation = await project.GetCompilationAsync(cts).ConfigureAwait(false)
            ?? throw new InvalidOperationException($"could not compile {projectFilePath}");

        var map = new McDcMap { ModuleId = Guid.NewGuid().ToString("N") };
        var baseDir = fileSystem.Path.GetDirectoryName(project.FilePath)!;

        foreach (var document in project.Documents)
        {
            var relativePath = fileSystem.Path.GetRelativePath(baseDir, document.FilePath!);
            if (IsBuildOutput(relativePath))
            {
                // generated by the build (AssemblyInfo, global usings): the mirror's build regenerates them
                continue;
            }
            if (relativePath.StartsWith("..", StringComparison.Ordinal))
            {
                throw new NotSupportedException($"{document.FilePath} is outside the project directory");
            }

            var tree = await document.GetSyntaxTreeAsync(cts).ConfigureAwait(false);
            var model = compilation.GetSemanticModel(tree!);
            var rewriter = new DecisionRewriter(model, map, relativePath.Replace('\\', '/'));
            var root = (CompilationUnitSyntax)rewriter.Visit(await tree!.GetRootAsync(cts).ConfigureAwait(false))!;

            var newPath = fileSystem.Path.Combine(outputDir, relativePath);
            fileSystem.Directory.CreateDirectory(fileSystem.Path.GetDirectoryName(newPath)!);
            fileSystem.File.WriteAllText(newPath, WithPrologue(root, document.FilePath!).ToFullString());
        }

        fileSystem.File.WriteAllText(
            fileSystem.Path.Combine(outputDir, McDcRuntimeSource.FileName),
            McDcRuntimeSource.Generate(map.ModuleId, fileSystem.Path.Combine(outputDir, HitsDirectoryName)));

        var mapFileName = fileSystem.Path.GetFileNameWithoutExtension(project.FilePath!) + McDcMap.FileSuffix;
        fileSystem.File.WriteAllText(fileSystem.Path.Combine(outputDir, mapFileName), map.ToJson());

        fileSystem.File.Copy(project.FilePath!, fileSystem.Path.Combine(outputDir, fileSystem.Path.GetFileName(project.FilePath!)), overwrite: true);

        return map;
    }

    private static bool IsBuildOutput(string relativePath) =>
        relativePath.StartsWith("obj", StringComparison.OrdinalIgnoreCase) && relativePath.Length > 3 && (relativePath[3] == '/' || relativePath[3] == '\\') ||
        relativePath.StartsWith("bin", StringComparison.OrdinalIgnoreCase) && relativePath.Length > 3 && (relativePath[3] == '/' || relativePath[3] == '\\');

    /*
     * Warnings off (the wrapped conditions lose nullable flow state, and warnings-as-errors would break
     * the build), and #line back to the original file, so that diagnostics, stack traces and the
     * debugger point at the original source.
     */
    public static CompilationUnitSyntax WithPrologue(CompilationUnitSyntax root, string originalPath)
    {
        // the file name isn't an escaped string: Razor writes #line "C:\dir\file.cshtml" too
        var prologue = SyntaxFactory.ParseLeadingTrivia($"#pragma warning disable\n#line 1 \"{originalPath}\"\n");

        var first = root.GetFirstToken(includeZeroWidth: true);
        return root.ReplaceToken(first, first.WithLeadingTrivia(prologue.AddRange(first.LeadingTrivia)));
    }
}
