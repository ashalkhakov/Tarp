using FluentAssertions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using System.IO.Abstractions;
using Tarp.McDc;

namespace TarpTests.McDc;

// the instrumenter Tarp.targets runs during a build, on a project in a temporary directory
[TestClass]
public class McDcBuildInstrumenterTests
{
    private string _project = "";

    [TestInitialize]
    public void CreateProject()
    {
        _project = Path.Combine(Path.GetTempPath(), "tarp-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(Path.Combine(_project, "obj", "Debug"));
    }

    [TestCleanup]
    public void DeleteProject() => Directory.Delete(_project, recursive: true);

    private static readonly string[] References =
        ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator);

    private void Write(string relativePath, string text)
    {
        var path = Path.Combine(_project, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
    }

    private McDcBuildRequest Request(params string[] sources)
    {
        var lines = new List<string>
        {
            "project-name=Proj",
            $"project-dir={_project}",
            "assembly-name=Proj",
            "target-framework=net8.0",
            $"intermediate-dir={Path.Combine(_project, "obj", "Debug")}/",
            $"output-dir={Path.Combine(_project, "obj", "Debug", "tarp")}/",
            $"results-dir={Path.Combine(_project, "results")}/",
            "nullable=enable",
            "define=DEBUG"
        };
        lines.AddRange(References.Select(r => "reference=" + r));
        lines.AddRange(sources.Select(s => $"source={s}|{Path.Combine(_project, s)}"));
        return McDcBuildRequest.Parse(lines);
    }

    private static McDcMap Instrument(McDcBuildRequest request, StringWriter? log = null) =>
        new McDcBuildInstrumenter(new FileSystem(), log ?? new StringWriter()).Instrument(request);

    private string Output(string name) => Path.GetFullPath(Path.Combine(_project, "obj", "Debug", "tarp", name));

    private const string Rules = @"
using System.Diagnostics.CodeAnalysis;

public static class Rules
{
    public static bool CanShip(bool paid, bool inStock, bool backorder) => (paid && inStock) || backorder;

    [ExcludeFromCodeCoverage]
    public static bool Excluded(bool a, bool b) => a && b;

    public static int Dynamic(dynamic d) { if (d) return 1; return 0; }
}";

    [TestMethod]
    public void ParsesTheArgumentsFile()
    {
        var r = McDcBuildRequest.Parse(new[] { "assembly-name=A", "define=X", "define=", "source=a\\b.cs|/p/a/b.cs", "allow-unsafe=True", "bogus" });

        r.AssemblyName.Should().Be("A");
        r.Defines.Should().Equal("X");
        r.Sources.Should().Equal(("a\\b.cs", "/p/a/b.cs"));
        r.AllowUnsafe.Should().BeTrue();
    }

    [TestMethod]
    public void InstrumentsTheProjectsOwnSources()
    {
        Write("Rules.cs", Rules);
        Write("obj/Debug/Proj.AssemblyInfo.cs", "[assembly: System.Reflection.AssemblyTitle(\"Proj\")]");
        Write("Generated.cs", "// <auto-generated/>\npublic static class Gen { public static bool F(bool a, bool b) => a && b; }");

        var map = Instrument(Request("Rules.cs", "obj/Debug/Proj.AssemblyInfo.cs", "Generated.cs"));

        map.Decisions.Select(d => (d.File, d.Text)).Should().Equal(("Proj/Rules.cs", "(paid && inStock) || backorder"));
        map.Skipped.Select(s => (s.Text, s.Reason)).Should().Equal(("d", "a condition is not a bool"));

        File.ReadAllLines(Output("replaced.txt")).Should().Equal("Rules.cs");
        File.ReadAllLines(Output("instrumented.txt")).Should().Equal(Output("src/Rules.cs"), Output(McDcRuntimeSource.FileName));
        McDcMap.FromJson(File.ReadAllText(Output("Proj.net8.0.map.json"))).ModuleId.Should().Be(map.ModuleId);

        // what the compiler gets instead: the untouched sources, plus the instrumented ones
        var sources = new[] { "obj/Debug/Proj.AssemblyInfo.cs", "Generated.cs" }.Select(s => Path.Combine(_project, s))
            .Concat(File.ReadAllLines(Output("instrumented.txt")));
        var compilation = CSharpCompilation.Create("Proj",
            sources.Select(p => CSharpSyntaxTree.ParseText(File.ReadAllText(p), path: p)),
            References.Select(r => MetadataReference.CreateFromFile(r)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
    }

    [TestMethod]
    public void AnUnchangedProjectKeepsItsOutputs()
    {
        Write("Rules.cs", Rules);
        var first = Instrument(Request("Rules.cs"));

        var old = new DateTime(2020, 1, 1, 0, 0, 0, DateTimeKind.Utc);
        File.SetLastWriteTimeUtc(Output("src/Rules.cs"), old);
        File.SetLastWriteTimeUtc(Output(McDcRuntimeSource.FileName), old);

        var second = Instrument(Request("Rules.cs"));

        second.ModuleId.Should().Be(first.ModuleId, "hits recorded against the first build still apply");
        File.GetLastWriteTimeUtc(Output("src/Rules.cs")).Should().Be(old, "rewriting it would recompile the project");
        File.GetLastWriteTimeUtc(Output(McDcRuntimeSource.FileName)).Should().Be(old);
    }

    [TestMethod]
    public void ErrorsThatWereThereBeforeDontStopInstrumentation()
    {
        // e.g. a member the instrumenter can't see (a generator it couldn't load)
        Write("Rules.cs", Rules + "\npublic static class Broken { public static Missing M() => null; }");

        var map = Instrument(Request("Rules.cs"));

        map.Decisions.Should().ContainSingle(d => d.Text == "(paid && inStock) || backorder");
        File.ReadAllLines(Output("replaced.txt")).Should().Equal("Rules.cs");
    }

    [TestMethod]
    public void FilesThatDontParseAreLeftAlone()
    {
        Write("Rules.cs", Rules);
        Write("Future.cs", "public static class Future { public static bool F(bool a, bool b) => a && b }");
        var log = new StringWriter();

        var map = Instrument(Request("Rules.cs", "Future.cs"), log);

        map.Decisions.Should().ContainSingle();
        File.ReadAllLines(Output("replaced.txt")).Should().Equal("Rules.cs");
        log.ToString().Should().Contain("not instrumenting").And.Contain("Future.cs");
    }
}
